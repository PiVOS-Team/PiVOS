int32_t loader_prepare_proc(struct proc* new_proc, int image_id) {
    struct proc_image img = images[image_id];
    struct mem_reg proc_mem_reg = {
        .base = 0x0,
        .size = MB_IN_B,
        .mem_type = MEM_TYPE_NORMAL_NO_CACHE
    };

    mem_map_reg(&new_proc->mem_ctx, &proc_mem_reg, MEM_MAP_ALLOC);
    mem_set_usr_ctx(&new_proc->mem_ctx, new_proc->PID);
    proc_init_ctx(new_proc, (void*)IMAGE_OFFSET, (void*)IMAGE_OFFSET);
    bytecpy((void*)IMAGE_OFFSET, img.img, img.size);

    return 1;
}

